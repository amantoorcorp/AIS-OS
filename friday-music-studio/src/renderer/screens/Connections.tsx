import { useEffect, useState } from 'react';
import { api } from '../api';
import { Badge, ErrorBanner, Section } from '../components/common';
import type { ProviderInfo } from '../../shared/types';

export function Connections() {
  const [providers, setProviders] = useState<ProviderInfo[]>([]);
  const [error, setError] = useState<string | null>(null);
  useEffect(() => {
    api.listProviders().then(setProviders).catch((e: Error) => setError(e.message));
  }, []);

  return (
    <div className="screen">
      <h1>Connections</h1>
      <ErrorBanner error={error} />
      <Section title="Music providers">
        <ul className="list">
          {providers.map((p) => (
            <li key={p.id} className="stack">
              <div>
                <strong>{p.label}</strong>{' '}
                {p.isMock ? <Badge tone="mock">MOCK</Badge> : p.state === 'ready' ? <Badge tone="ok">Connected</Badge> : <Badge tone="bad">Not configured</Badge>}
              </div>
              <div className="muted">{p.detail}</div>
            </li>
          ))}
        </ul>
        <p className="muted small-text">
          A real Suno adapter will only be built from official, authorised API documentation and your own credentials. Until then no endpoints,
          prices or limits are assumed, and nothing generated by the mock provider is real music.
        </p>
      </Section>
      <Section title="YouTube">
        <div>
          <Badge tone="bad">Not configured</Badge> <span className="muted">Planned for Phase 3</span>
        </div>
        <p className="muted small-text">
          Phase 3 adds Google's Desktop OAuth flow in your system browser (PKCE, state check, loopback callback), the minimum upload scope,
          encrypted token storage via your OS keychain, and one approved PRIVATE test upload. It needs a Google Cloud project with the YouTube
          Data API enabled and a Desktop OAuth client that you create.
        </p>
      </Section>
    </div>
  );
}
